import assert from "node:assert/strict";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "playwright";
import { login, baseURL } from "./smoke-dsh-helpers.mjs";
const fixturePath = resolve(".cache/collaboration/fixture.json");
const fixture = JSON.parse(await readFile(fixturePath, "utf8"));
assert(new URL(fixture.url).hostname === "127.0.0.1", "fixture must use loopback");
const out = resolve(".cache/collaboration/dual");
await mkdir(out, { recursive: true });
const browser = await chromium.launch(), errors = [];
const api = async (actor, path, method = "GET", data) => {
  const response = await fetch(fixture.url + path, { method, headers: { Cookie: `workagent-session=${fixture[actor]}`, Origin: fixture.url, "Content-Type": "application/json" }, ...(data ? { body: JSON.stringify(data) } : {}) });
  return { status: response.status, body: await response.text(), headers: Object.fromEntries(response.headers) };
};
const setup = async (actor) => {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.on("pageerror", (error) => errors.push(error.message));
  for (const name of ["client.js", "tokens.css"]) await page.route(`**/plugins/@workagent/dsh-client/${name}*`, (route) => route.fulfill({ path: resolve(`packages/dsh-client-workagent/${name}`), contentType: name.endsWith("css") ? "text/css" : "text/javascript" }));
  await page.route(/\/api\/portal\/shared-/, async (route) => {
    const request = route.request(), url = new URL(request.url());
    if (url.pathname.endsWith("shared-events")) return route.fulfill({ contentType: "text/event-stream", body: ": fixture uses reconciliation polling\n\n" });
    const data = request.postData() ? request.postDataJSON() : undefined;
    const response = await api(actor, url.pathname + url.search, request.method(), data);
    await route.fulfill(response);
  });
  await login(page);
  await page.goto(`${baseURL}/?frontend=dsh&workagent=shared`);
  return page;
};
try {
  const owner = await setup("owner"), member = await setup("member");
  await owner.getByRole("button", { name: "新建协作项目", exact: true }).last().click();
  const create = owner.getByRole("dialog", { name: "新建协作项目", exact: true });
  await create.getByLabel("共享项目名称").fill("双员工集成验收");
  await create.getByRole("button", { name: "创建项目", exact: true }).click();
  await owner.getByLabel("共享消息", { exact: true }).waitFor();
  const project = new URL(owner.url()).searchParams.get("project");
  const discussion = new URL(owner.url()).searchParams.get("discussion");
  assert(project && discussion);
  const invited = await api("owner", `/api/portal/shared-projects/${project}/invites`, "POST", { targetUsername: "bob", expiresInHours: 72 });
  assert.equal(invited.status, 201, invited.body);
  await member.evaluate(() => window.dispatchEvent(new Event("focus")));
  await member.getByRole("button", { name: "查看邀请", exact: true }).click();
  await member.getByRole("dialog", { name: "项目邀请", exact: true }).getByRole("button", { name: "接受", exact: true }).click();
  await member.getByRole("heading", { name: "双员工集成验收", exact: true }).waitFor();
  const send = async (page, body) => {
    await page.getByLabel("共享消息", { exact: true }).fill(body);
    await page.locator(".workagent-collab-chat").getByRole("button", { name: "发送消息", exact: true }).click();
    await page.getByText(body, { exact: true }).waitFor();
  };
  await send(owner, "负责人先提交用户反馈。");
  await member.evaluate(() => window.dispatchEvent(new Event("focus")));
  await member.getByText("负责人先提交用户反馈。", { exact: true }).waitFor();
  await send(member, "同事补充：请保持普通讨论。");
  await owner.evaluate(() => window.dispatchEvent(new Event("focus")));
  await owner.getByText("同事补充：请保持普通讨论。", { exact: true }).waitFor();
  await member.reload();
  await member.getByText("同事补充：请保持普通讨论。", { exact: true }).waitFor();
  let messages = JSON.parse((await api("owner", `/api/portal/shared-messages?conversation_id=${discussion}`)).body).messages;
  assert.equal(messages.filter((message) => message.kind === "assistant").length, 0);
  const configured = await api("owner", `/api/portal/shared-conversations/${discussion}/assistant`, "PUT", { assistant_id: "codex", assistant_backend: "codex", model_id: "gpt-5", thinking_effort: "medium" });
  assert.equal(configured.status, 200, configured.body);
  await member.evaluate(() => window.dispatchEvent(new Event("focus")));
  await member.getByPlaceholder(/输入 @ 邀请助手/).waitFor();
  await member.getByLabel("共享消息", { exact: true }).fill("@");
  await member.getByRole("option", { name: /助手.*本条/ }).click();
  await member.locator(".workagent-collab-chat").getByRole("button", { name: "发送消息", exact: true }).click();
  await member.getByText("Shared answer", { exact: true }).waitFor();
  await send(member, "下一条无需助手。");
  messages = JSON.parse((await api("owner", `/api/portal/shared-messages?conversation_id=${discussion}`)).body).messages;
  assert.equal(messages.filter((message) => message.kind === "assistant").length, 1);
  await owner.screenshot({ path: `${out}/owner.png` });
  await member.screenshot({ path: `${out}/member.png` });
  const removed = await api("owner", `/api/portal/shared-projects/${project}/members/2`, "DELETE");
  assert([200, 204].includes(removed.status), removed.body);
  await member.evaluate(() => window.dispatchEvent(new Event("focus")));
  await member.getByText("项目不存在，或你已没有访问权限。", { exact: true }).waitFor();
  const denied = await api("member", `/api/portal/shared-messages?conversation_id=${discussion}`);
  assert([403, 404].includes(denied.status));
  assert.deepEqual(errors, []);
  await writeFile(`${out}/report.json`, JSON.stringify({ checks: ["real isolated Portal", "two employees", "accept invitation", "same project", "ordinary discussion", "reload", "explicit assistant only", "revoked access"], project, discussion, assistantRuns: 1, errors }, null, 2));
} finally { await browser.close(); await writeFile(fixturePath + ".stop", "done"); }
