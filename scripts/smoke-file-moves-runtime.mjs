import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { mkdtemp, mkdir, writeFile, readFile } from "node:fs/promises";
import { createServer } from "node:http";

const [profile, evidence] = process.argv.slice(2);
assert(profile && evidence, "profile and isolated evidence directory required");
const require = createRequire(join(profile, "package.json"));
const bundle = dirname(require.resolve("@workagent/harness-bundle"));
const { WorkspaceStore } = await import(pathToFileURL(join(bundle, "workspace-store.js")));
const { WorkspaceController } = await import(pathToFileURL(join(bundle, "workspace-api.js")));
const { nativeFileInput } = await import(pathToFileURL(join(bundle, "native-images.js")));
await import(pathToFileURL(join(bundle, "runtime.js")));
await mkdir(evidence, { recursive: true });
const scratch = await mkdtemp(join(evidence, "file-moves-fixture-"));
const root = join(scratch, "projects"), home = join(scratch, "home");
let store = new WorkspaceStore(root, home);
const project = store.create("move-acceptance");
const file = store.write(project.id, "文书.txt", Buffer.from("original"));
store.write(project.id, "notes.txt", Buffer.from("notes"));
store.registerArtifact(project.id, "session", file.path);
let handler; const disposers = [];
new WorkspaceController({ effect: fn => { const dispose = fn(); if (typeof dispose === "function") disposers.push(dispose); }, webServer: { register: route => { handler = route.handler; return () => {}; } } }, "isolated-file-moves-token", store, () => project.id);
const server = createServer((req, res) => { void handler(req, res); });
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const base = `http://127.0.0.1:${server.address().port}/v1/workspaces/${project.id}`;
const headers = { authorization: "Bearer isolated-file-moves-token", "content-type": "application/json" };
const post = async input => {
  const res = await fetch(base + "/move", { method: "POST", headers, body: JSON.stringify(input) });
  return { status: res.status, body: await res.json() };
};
const checks = [];
try {
  assert.equal((await fetch(base + "/files")).status, 401);
  assert.equal((await post({ moves: [{ source: file.path, destination: "../escape" }] })).status, 400);
  checks.push("authenticated API and project confinement");
  store.moves.busy = () => true;
  const queued = await post({ moves: [{ source: file.path, destination: "历史/文书.txt", fileId: file.fileId }, { source: "notes.txt", destination: "历史/notes.txt" }] });
  assert.equal(queued.status, 202); assert.equal(queued.body.state, "queued");
  await post({ action: "lease", owner: "editor-immutable", path: file.path });
  store.moves.busy = () => false; store.moves.drain(project.id);
  assert.equal(store.moves.list(project.id)[0].state, "queued");
  store.editText(project.id, file.path, "original", "saved before move");
  await post({ action: "lease", owner: "editor-immutable" });
  store.moves.drain(project.id);
  assert.equal(store.read(project.id, "历史/文书.txt").toString(), "saved before move");
  checks.push("running task and dirty-editor deferral with saved bytes preserved");
  const response = await fetch(`${base}/content?path=${encodeURIComponent(file.path)}&fileId=${file.fileId}`, { headers });
  assert.equal(response.status, 200); assert.equal(await response.text(), "saved before move");
  assert.equal(store.listAssets(project.id, "session")[0].path, "历史/文书.txt");
  const replacement = store.write(project.id, file.path, Buffer.from("replacement"));
  assert.notEqual(file.fileId, replacement.fileId);
  assert.equal(store.locate(project.id, file.path, file.fileId).path, "历史/文书.txt");
  assert.equal(store.locate(project.id, file.path, replacement.fileId).path, file.path);
  checks.push("stable downloads, old links, artifact records and reused-path identity");
  assert(nativeFileInput(store, project.id, `项目文件：${JSON.stringify({ ...file, workspaceId: project.id })}`).includes("历史"));
  const changes = store.moves.context(project.id);
  assert(changes.text.includes("历史")); assert.equal(store.moves.context(project.id, changes.revision).text, "");
  assert.equal((await post({ action: "undo", id: queued.body.id })).status, 409);
  assert.equal(store.read(project.id, file.path).toString(), "replacement");
  checks.push("engine reference resolution, incremental context and collision-safe undo");
  store.delete(project.id, replacement.path);
  const undo = await post({ action: "undo", id: queued.body.id }); assert.equal(undo.body.state, "completed");
  for (const dispose of disposers.splice(0)) dispose();
  store = new WorkspaceStore(root, home);
  assert.equal(store.locate(project.id, file.path, file.fileId).path, file.path);
  assert.equal(store.read(project.id, file.path).toString(), "saved before move");
  checks.push("undo and restart persistence");
  const report = { status: "passed", profile, checks, scratch };
  await writeFile(join(evidence, "file-moves-runtime-smoke.json"), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally { for (const dispose of disposers) dispose(); await new Promise(resolve => server.close(resolve)); }
