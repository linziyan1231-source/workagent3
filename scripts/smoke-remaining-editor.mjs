import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {baseURL,json,withPage} from './smoke-dsh-helpers.mjs';
const evidence=process.env.WORKAGENT_SMOKE_EVIDENCE_DIR;
const previous=JSON.parse(await readFile(join(evidence,'remaining-capabilities.json'),'utf8'));
const report={checks:[]};
await withPage(async page=>{
 page.on('dialog',dialog=>dialog.accept());
 const path=`/api/runtime/v1/workspaces/${previous.workspace}/content`;
 for(const name of ['source.txt','second.txt']) await json(page,`${path}?path=${name}`,{method:'PUT',headers:{'Content-Type':'application/octet-stream'},body:`original ${name}\nsecond line\n`});
 await page.goto(`${baseURL}/?frontend=dsh&session=${previous.session}`);
 await page.getByLabel('当前会话模型').waitFor();
 const open=page.getByRole('button',{name:'打开文件侧栏',exact:true});if(await open.count())await open.click();
 const panel=page.getByRole('complementary',{name:'项目文件侧栏'});
 await panel.getByRole('button',{name:'source.txt',exact:true}).click();
 await panel.getByRole('button',{name:'编辑文件',exact:true}).click();
 await panel.getByLabel('编辑文件内容').fill('DRAFT_SURVIVES_TABS\nsecond line\n');
 await panel.getByRole('button',{name:'返回文件列表',exact:true}).click();
 await panel.getByRole('button',{name:'second.txt',exact:true}).click();
 await panel.getByLabel('切换文件 source.txt',{exact:true}).click();
 assert.match(await panel.getByLabel('编辑文件内容').inputValue(),/DRAFT_SURVIVES_TABS/);
 report.checks.push('多文件切换保留未保存编辑');
 await page.reload();await page.getByLabel('当前会话模型').waitFor();
 if(await open.count())await open.click();
 await panel.getByRole('button',{name:'source.txt',exact:true}).click();
 await panel.getByRole('button',{name:'编辑文件',exact:true}).click();
 assert.match(await panel.getByLabel('编辑文件内容').inputValue(),/DRAFT_SURVIVES_TABS/);report.checks.push('刷新后恢复编辑草稿');
 await panel.getByRole('button',{name:'查看修改对比',exact:true}).click();
 await panel.getByRole('button',{name:'返回编辑',exact:true}).waitFor();
 await page.screenshot({path:join(evidence,'remaining-editor-diff.png'),animations:'disabled'});
 await panel.getByRole('button',{name:'返回编辑',exact:true}).click();
 await panel.getByRole('button',{name:'保存文件',exact:true}).click();
 await panel.getByRole('button',{name:'编辑文件',exact:true}).waitFor();
 assert.match(await(await page.request.get(`${baseURL}${path}?path=source.txt`)).text(),/DRAFT_SURVIVES_TABS/);report.checks.push('修改对比及实际保存');
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:join(evidence,'remaining-editor-mobile.png'),animations:'disabled'});
 assert.ok(await panel.isVisible());report.complete=true;
}).finally(async()=>{await writeFile(join(evidence,'remaining-editor.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));});
